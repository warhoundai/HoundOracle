"""Synthetic local OCR stress test; not Google/reCAPTCHA or independent real-world accuracy."""

import argparse
import hashlib
import io
import json
import random
import statistics
import string
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

from houndoracle.captcha import solve_text_captcha


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--per-family", type=int, default=8)
    args = parser.parse_args()
    if not 1 <= args.per_family <= 50:
        parser.error("per-family must be1..50")
    rng = random.Random(2501)
    font_path = Path("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf")
    font = ImageFont.truetype(str(font_path), 40)
    rows = []
    families = [
        ("digits", string.digits, False, False),
        ("uppercase", string.ascii_uppercase + string.digits, False, False),
        ("mixed", string.ascii_letters + string.digits, False, False),
        ("noisy-uppercase", string.ascii_uppercase + string.digits, True, False),
        ("rotated-mixed", string.ascii_letters + string.digits, False, True),
    ]
    for family, alphabet, noisy, rotated in families:
        for index in range(args.per_family):
            expected = "".join(rng.choice(alphabet) for _ in range(5))
            image = Image.new("RGB", (220, 72), "white")
            draw = ImageDraw.Draw(image)
            draw.text((10, 8), expected, fill="black", font=font)
            if noisy:
                for _ in range(100):
                    x, y = rng.randrange(220), rng.randrange(72)
                    draw.point((x, y), fill=(90, 90, 90))
                for _ in range(2):
                    draw.line(
                        (
                            rng.randrange(220),
                            rng.randrange(72),
                            rng.randrange(220),
                            rng.randrange(72),
                        ),
                        fill=(130, 130, 130),
                        width=1,
                    )
            if rotated:
                image = image.rotate(rng.choice([-10, -7, 7, 10]), fillcolor="white")
            stream = io.BytesIO()
            image.save(stream, format="PNG")
            raw = stream.getvalue()
            for backend in ["tesseract", "ddddocr"]:
                result = solve_text_captcha(
                    raw, backend=backend, alphabet=alphabet, expected_length=5
                )
                rows.append(
                    {
                        "family": family,
                        "index": index,
                        "image_sha256": hashlib.sha256(raw).hexdigest(),
                        "expected": expected,
                        "exact_match": result["candidate"] == expected,
                        **result,
                    }
                )
            print(f"completed {family}/{index + 1}", flush=True)
    summary = {}
    for backend in ["tesseract", "ddddocr"]:
        selected = [r for r in rows if r["backend"] == backend]
        latency = sorted(r["latency_seconds"] for r in selected)
        summary[backend] = {
            "count": len(selected),
            "exact_matches": sum(r["exact_match"] for r in selected),
            "exact_match_fraction": statistics.mean(r["exact_match"] for r in selected),
            "p50_seconds": statistics.median(latency),
            "p95_seconds": latency[max(0, __import__("math").ceil(0.95 * len(latency)) - 1)],
            "families": {
                f: {
                    "correct": sum(r["exact_match"] for r in selected if r["family"] == f),
                    "count": sum(r["family"] == f for r in selected),
                }
                for f, *_ in families
            },
        }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(
            {
                "protocol": {
                    "seed": 2501,
                    "per_family": args.per_family,
                    "font_sha256": hashlib.sha256(font_path.read_bytes()).hexdigest(),
                    "scope": "Synthetic stress cases generated by this script; no real-site acceptance or Google challenge evaluation; includes case-sensitive errors. No tuning or calibrated confidence.",
                },
                "summary": summary,
                "records": rows,
            },
            indent=2,
        )
        + "\n"
    )
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
