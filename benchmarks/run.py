"""Synthetic controlled-language smoke benchmark; never a real-world quality claim."""

import argparse
import hashlib
import json
import platform
import resource
import statistics
import time
from pathlib import Path

from houndoracle import DocumentInput, Oracle
from houndoracle.calibration import Calibration, CalibrationBin
from houndoracle.compiler import compile_question
from houndoracle.evaluators import symbolic


def populate(oracle, prefix, count, now):
    for i in range(count):
        oracle.store.ingest(
            DocumentInput(
                url=f"https://example.org/{prefix}/{i}",
                text=f"{prefix}{i} was released in {2020 + i % 5}.",
                origin=f"{prefix}-primary-{i}",
                observed_at=now,
                expires_at=now + 86400,
                reviewed=True,
                primary=True,
            )
        )


def wilson(errors, count):
    if not count:
        return None
    z, p = 1.959963984540054, errors / count
    center = (p + z * z / (2 * count)) / (1 + z * z / count)
    radius = z * ((p * (1 - p) / count + z * z / (4 * count * count)) ** 0.5) / (1 + z * z / count)
    return [max(0, center - radius), min(1, center + radius)]


def measure(oracle, cases):
    rows = []
    for question, label in cases:
        result = oracle.verify(question)
        rows.append(
            {
                "question": question,
                "expected": label,
                "decision": result.decision.value,
                "reason": result.reason,
                "latency_seconds": result.usage["latency_seconds"],
                "cache_hit": result.cache_hit,
            }
        )
    definitive = [r for r in rows if r["decision"] in ("YES", "NO")]
    errors = sum(r["decision"] != r["expected"] for r in definitive)
    latencies = sorted(r["latency_seconds"] for r in rows)
    return {
        "count": len(rows),
        "coverage": len(definitive) / len(rows),
        "selective_risk": errors / len(definitive) if definitive else None,
        "selective_risk_95pct_wilson_interval": wilson(errors, len(definitive)),
        "decision_match_fraction": sum(r["decision"] == r["expected"] for r in rows) / len(rows),
        "latency_seconds": {
            "p50": statistics.median(latencies),
            "p95": latencies[int(0.95 * (len(latencies) - 1))],
        },
        "cache_hits": sum(r["cache_hit"] for r in rows),
        "rows": rows,
    }


def run():
    now = time.time()
    # Fixed disjoint entity/source families. Synthetic labels are generated by construction.
    calibration_engine = Oracle()
    populate(calibration_engine, "CalibrationWidget", 100, now)
    correct, records = 0, []
    for i in range(100):
        for offset in (0, 1):
            for negate in (False, True):
                question = f"Was CalibrationWidget{i} {'not ' if negate else ''}released in {2020 + i % 5 + offset}?"
                claim = compile_question(question)
                relations = calibration_engine.compiler.evaluate(
                    claim, calibration_engine.store.documents()
                )
                verdict = symbolic(claim, relations)
                expected = (offset == 0) != negate
                correct += verdict == expected
                records.append([question, expected, verdict])
    digest = hashlib.sha256(json.dumps(records, sort_keys=True).encode()).hexdigest()
    artifact = Calibration(
        policy_id=calibration_engine.policy_id,
        population="synthetic-controlled-release-records-only; NOT production qualification",
        supported_kinds=["release_year", "not"],
        expires_at=now + 86400,
        dataset_digest=digest,
        bins=[CalibrationBin(lower=0.5, upper=1, correct=correct, count=len(records))],
    )
    oracle = Oracle()
    populate(oracle, "TestWidget", 40, now)
    cases = []
    for i in range(40):
        year = 2020 + i % 5
        cases.extend(
            [
                (f"Was TestWidget{i} released in {year}?", "YES"),
                (f"Was TestWidget{i} released in {year + 1}?", "NO"),
                (f"Was TestWidget{i} not released in {year}?", "NO"),
            ]
        )
    cases.extend([(f"Was MissingWidget{i} released in 2024?", "MAYBE") for i in range(20)])
    cases.extend([(f"Is TestWidget{i} safe?", "MAYBE") for i in range(20)])
    default = measure(oracle, cases)
    oracle.calibration = artifact
    cold = measure(oracle, cases)
    warm = measure(oracle, cases)
    return {
        "schema_version": 1,
        "benchmark": "synthetic controlled-language smoke, not independent evaluation",
        "environment": {
            "python": platform.python_version(),
            "platform": platform.platform(),
            "max_rss_kib_linux": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
        },
        "test_digest": hashlib.sha256(json.dumps(cases).encode()).hexdigest(),
        "calibration": artifact.model_dump(mode="json"),
        "default_uncalibrated": default,
        "synthetic_calibrated_cold": cold,
        "synthetic_calibrated_warm": warm,
        "cost": {"external_requests": 0, "provider_charges_usd": 0, "host_cost_usd": None},
        "limitations": [
            "No live search, FIRE reproduction, trained NLI, or human real-world gold labels.",
            "Synthetic calibration does not qualify a production deployment.",
            "Intervals treat examples as independent; shared templates violate that assumption.",
            "No cost/latency/reliability advantage is established.",
        ],
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = run()
    args.output.write_text(json.dumps(result, indent=2) + "\n")
    print(
        json.dumps(
            {
                key: {k: v for k, v in result[key].items() if k != "rows"}
                for key in [
                    "default_uncalibrated",
                    "synthetic_calibrated_cold",
                    "synthetic_calibrated_warm",
                ]
            },
            indent=2,
        )
    )
